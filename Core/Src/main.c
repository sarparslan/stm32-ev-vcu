/* DiagTask body: dump the trace every CAN_TRACE_PERIOD_MS. Low priority,
   the slow printf lives here -> never blocks the critical ControlTask. */
void StartDiagTask(void *argument)
{
  (void)argument;
  for(;;)
  {
    App_DiagStep();
    osDelay(CAN_TRACE_PERIOD_MS);
  }
}

/* CanRxTask body: start CAN, then process frames from the queue.
   Blocks while the queue is empty (no CPU spent), wakes on arrival. */
void StartCanRxTask(void *argument)
{
  (void)argument;
  CanBus_Start();                  /* filter + start + RX interrupt */
  for(;;)
  {
    CanBus_ProcessRx(osWaitForever);
  }
}

